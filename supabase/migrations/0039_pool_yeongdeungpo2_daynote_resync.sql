-- Pool's day v1 — 영등포제2스포츠센터(POOL_SEOUL_0007) 일요일 안내문구 재동기화.
-- 표준(사용자 확정 2026-05-16): "매월 {주차} 일요일에만 운영합니다."
--   복수 주차는 쉼표(2, 4), 가운뎃점 금지, 요일어('일요일') 포함.
-- 0033에서 이미 표준값으로 정정했으나 DB 미반영 상태 → 본 마이그레이션으로 재설정.
-- 다른 요일 안내문구가 추가돼도 안 깨지게 "일" 키만 jsonb 병합(||)으로 갱신. 멱등.
-- 전제: by_day["일"]에 슬롯 1개 이상(0031 INSERT에서 일요일 슬롯 존재) → 제약 충족.

update public.schedules
set day_notes =
  coalesce(day_notes, '{}'::jsonb)
  || $${"일":"매월 2, 4주차 일요일에만 운영합니다."}$$::jsonb
where pool_id = 'POOL_SEOUL_0007';
