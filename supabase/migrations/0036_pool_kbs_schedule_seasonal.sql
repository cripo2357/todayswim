-- Pool's Day v1 — KBS스포츠월드(POOL_SEOUL_0008) 시간표 공식 정정 + 하절기 그룹.
-- 출처: 공식 kbssw.co.kr (WebFetch는 SSL 체인 오류 → curl -k 로 취득; 페이지 인코딩
--   깨졌으나 시각은 ASCII라 신뢰 가능 + Figma 144:3716의 하절기 수치와 정확 일치 = 교차검증).
-- 0034는 cbswim 기준(토·일 09:00~17:00 단일)이라 정정. 0034 ON CONFLICT → UPDATE.
--
-- 공식 자유수영:
--   · 평일(월~금) 13:30~15:30 (시즌 변동 없음 → flat, slot_groups 없음)
--   · 토·일 기본: 1부 09:00~12:30, 2부 13:30~17:00
--   · 하절기(6~9월): 1부 09:00~11:30, 2부 12:30~15:00, 3부 16:00~18:30
--   · 일요일 정기휴무: 매월 2·4째 일요일 (하절기는 휴장 없음) / 토요일 휴무 없음
-- 일요일 휴무 안내는 slot_groups의 '기본 운영' 라벨로 표기(Figma 144:3716) →
--   기존 day_notes(일)와 중복/모순 방지 위해 day_notes 비움.
-- by_day는 기본(레거시·요일칩·게이팅 기준) 유지, slot_groups는 토·일만(시즌 변동 있는 요일).

