-- 데이터는 운영자가 Supabase Dashboard에서 직접 관리 (announcements 와 동일 패턴).
-- 시드 데이터는 docs/SPEC.md 의 현행 기능(P1) 기준 — 톤앤매너는 따뜻하고 친근하게.
--
-- RLS: 전체 read, write 는 service_role 만.

create table if not exists public.faqs (
  id           uuid primary key default gen_random_uuid(),
  question     text not null,
  answer       text not null,
  -- 노출 순서. 작을수록 위. 빈도/중요도 기준 운영자 조정.
  sort_order   int not null default 0,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists faqs_sort_order_idx on public.faqs (sort_order asc);

alter table public.faqs enable row level security;

drop policy if exists faqs_read_all on public.faqs;
create policy faqs_read_all on public.faqs
  for select using (true);

