-- Pool's day — Phase 2: 동작삼일수영장(POOL_SEOUL_0011) day_notes 보강.
--
-- ## 정정 이력 (2회)
--
-- (a) 첫 작성: 자동 검증 배치 LLM이 "월~금 14:00 추가"라 감지해서 0053이 야간을
--     금만 본 게 오류라고 추정 → 월~금 야간 + 여성전용 안내 UPDATE.
-- (b) 운영자 사이트 직접 재확인: 야간 19:00–21:50은 **금요일만 맞음**.
--     "월~금"은 운영자의 두 번째 fetch에서 잘못 일반화한 표 해석.
--     0053 원본 by_day가 정확. 이번 마이그레이션 = day_notes(여성전용 안내)만 신규 추가.
--
-- ## 출처
--
-- https://sports.idongjak.or.kr/home/105 (운영자 사이트 직접 확인, 2026-05-20).
--
-- ## 보강 내용
--
-- - by_day: 0053 원본 유지 (재선언으로 idempotent — 잘못된 (a)가 적용됐어도 복구).
-- - day_notes: 월·수·금 08:00 슬롯은 여성전용(정원 30명) → 안내 추가.
--              일요일 셋째 주만 운영 안내는 0053에서 이미 있음 (재선언).

