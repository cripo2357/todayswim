-- Pool's day v1 — 요일 안내문구 톤 표준 확정 + 사당/영등포 정규화.
-- 표준(사용자 확정 2026-05-16): "매월 {주차} 일요일에만 운영합니다."
--   · 단일:  "매월 1주차 일요일에만 운영합니다."
--   · 복수:  "매월 2, 4주차 일요일에만 운영합니다." (주차는 쉼표, 요일어 '일요일' 포함)
-- 경위: 사당(0024) 원문은 "매월 1주차에만 운영합니다."였고, 사용자가 Supabase에서
--   "매월 1주차 일요일에만 운영합니다."로 직접 수정 → 마이그레이션을 그 값으로 동기화
--   (source of truth 일치, 재현성). 영등포(0032)의 "매월 2·4주차에만 운영합니다."도 표준으로.
-- 0024/0031/0032가 ON CONFLICT라 INSERT 재실행 무효 → day_notes UPDATE로 정정.
-- (멱등: 사당 행은 사용자 수동값과 동일해져 변화 없음.)

update public.schedules
