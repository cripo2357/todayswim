-- Pool's day — 창동문화체육센터(POOL_0031) 일요일 격주 휴관 day_note 추가.
--
-- 공식 자유수영 안내판 비고: "매월 1, 3, 5주 일요일 및 공휴일, 대체공휴일 정기휴무".
-- → 일요일은 2·4주차만 운영. by_day 슬롯 모델(요일 기반)이 주차 구분을 못 하므로
--   day_notes 로 안내문구 노출(0113 등록 직후 보강).
--
-- day_note_constraint: 일요일에 슬롯 3개(09/12/15시) 있음 → 슬롯 1개 이상이라 허용.
-- 톤 표준(2026-05-16): "매월 {주차} {요일}에만 운영합니다." 쉼표·요일어 포함.

update public.schedules set day_notes = $${
  "일": "매월 2, 4주차 일요일에만 운영합니다."
}$$::jsonb
where pool_id = 'POOL_0031';
